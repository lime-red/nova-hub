"""The golden image recipe: a game's media made into a clean, finished install.

make_golden.py runs it; the rig installs its games from what it makes, so the
nightly run plays the same images a hub is given. A BRE or FE image is the
game from its media with every trace of the donor's league taken out: no
bbs.cfg, no nodes file, nothing in DATA/, BULLETIN/, INBOUND/, OUTBOUND/,
NETMAIL/ or BACKUP/, no door drop files or batch files. GAME/ is regenerated by
`BREDATA -Y` / `FEDATA -Y`, which needs no bbs.cfg. The empty folders stay; the
games need them, and the manifest lists them.

Before it is packed, a copy is RESET as a throwaway one-node league (999) to
show RESET makes a game from it, and the image itself is checked for case
twins: two names Linux keeps apart and DOS reads as one.

Building runs dosemu, so it needs the user's dosemu and their drive_c; the work
is done inside drive_c, in 8.3 names, where DOS can reach it.
"""

import secrets
import shutil
import zipfile
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Callable, Optional

from backend.services.game_images import (
    ImageError,
    check_image,
    image_dirname,
    install_image,
    pack_image,
    sha256,
    write_manifest,
)

# Raise when the recipe changes what an image holds: the version names the
# recipe, so a new recipe makes a new image rather than a changed one.
RECIPE = 1

# Top-level files that belong to one board or one league, in any case. The
# media's route.cfg ("ROUTE * 2") sends a leaf node's mail to itself; no working
# install has one, as routing comes from the HOST line of the nodes file.
DROP = {
    "bbs.cfg", "brnodes.dat", "fenodes.dat", "brnodes.bak", "fenodes.bak",
    "inuse.flg", "route.cfg", "routes.lst", "routes.bad", "dupes.txt",
    "problems.log", "bbsinfo.lst", "doorfile.sr", "dorinfo1.def",
}
# Folders whose files are a league's state. Emptied; their subfolders stay.
EMPTY = ("DATA", "BULLETIN", "INBOUND", "OUTBOUND", "NETMAIL", "BACKUP")
TRIAL_LEAGUE = "999"


@dataclass(frozen=True)
class DosRecipe:
    game: str  # B or F
    exe: str  # BRE.EXE
    data_exe: str  # BREDATA.EXE, which -Y regenerates GAME/ with
    nodes_file: str
    required_data: tuple  # in DATA/ once RESET has run, any case

    @property
    def prefix(self) -> str:
        return {"B": "bre", "F": "fe"}[self.game]


RECIPES = {
    "B": DosRecipe("B", "BRE.EXE", "BREDATA.EXE", "BRNODES.DAT", ("GAME.DAT", "IDS.DAT", "PLANET.BRE")),
    # FE lays down only game.dat at RESET; the rest comes with the first run.
    "F": DosRecipe("F", "FE.EXE", "FEDATA.EXE", "FENODES.DAT", ("GAME.DAT",)),
}


class GoldenError(RuntimeError):
    """The recipe could not make a good image, and why."""


@dataclass
class Dosemu:
    """How to run DOS commands on this machine."""
    drive_c: Path
    dosemu: str = "/usr/bin/dosemu"
    conf: Optional[Path] = None
    log_dir: Path = Path(".")

    def command(self, folder: Path, batch: str) -> list:
        cmd = [self.dosemu]
        if self.conf:
            cmd += ["-f", str(self.conf)]
        return cmd + ["-K", str(folder), "-E", batch]

    def dos_path(self, folder: Path) -> str:
        rel = Path(folder).relative_to(self.drive_c)
        return "C:\\" + "\\".join(p.upper() for p in rel.parts)


def _crlf(*lines) -> bytes:
    return "".join(f"{line}\r\n" for line in lines).encode()


def _batch(folder: Path, name: str, dos_path: str, command: str):
    (folder / name).write_bytes(_crlf("@ECHO OFF", "C:", f"CD {dos_path}", command, "EXIT"))


def case_twins(folder: Path) -> list[str]:
    """Pairs of names in one folder that differ only in case: one name to DOS."""
    found = []
    for d in [folder, *sorted(p for p in folder.rglob("*") if p.is_dir())]:
        seen = {}
        for p in sorted(d.iterdir()):
            other = seen.setdefault(p.name.lower(), p.name)
            if other != p.name:
                found.append(f"{p.relative_to(folder).parent / other} and {p.name}")
    return found


def unpack_media(media: Path, into: Path) -> Path:
    """Unzip game media into `into` and return the game's folder in it (the
    one holding the EXEs). Refuses names that leave the folder."""
    with zipfile.ZipFile(media) as z:
        for name in z.namelist():
            path = PurePosixPath(name)
            if path.is_absolute() or ".." in path.parts:
                raise GoldenError(f"{media.name} holds {name!r}, outside its folder")
        z.extractall(into)
    exes = sorted(p.parent for p in into.rglob("*") if p.is_file() and p.suffix.upper() == ".EXE")
    if not exes:
        raise GoldenError(f"{media.name} holds no game")
    return min(exes, key=lambda p: len(p.parts))


def clean(folder: Path) -> list[str]:
    """Take a donor's league out of a game folder. Returns what went."""
    gone = []
    for p in sorted(folder.iterdir()):
        if p.is_file() and (p.name.lower() in DROP or p.suffix.lower() == ".bat"):
            p.unlink()
            gone.append(p.name)
    for name in EMPTY:
        d = _child(folder, name)
        if d.is_dir():
            for f in sorted(d.rglob("*")):
                if f.is_file():
                    f.unlink()
                    gone.append(f.relative_to(folder).as_posix())
        else:
            d.mkdir()
    return gone


def _child(folder: Path, name: str) -> Path:
    """`name` in folder, in whatever case it is there."""
    for p in folder.iterdir():
        if p.name.lower() == name.lower():
            return p
    return folder / name


def regenerate_game(folder: Path, recipe: DosRecipe, dos: Dosemu) -> None:
    """`BREDATA -Y`: rebuild GAME/ from the data EXE, in place."""
    from sr_harness.run import run as dosrun

    stem = recipe.data_exe.rsplit(".", 1)[0]
    _batch(folder, "GAMEDATA.BAT", dos.dos_path(folder), f"{stem} -Y")
    log = dos.log_dir / f"golden_{recipe.prefix}_gamedata.log"
    try:
        rc = dosrun(dos.command(folder, "GAMEDATA.BAT"), log, timeout=180)
    finally:
        (folder / "GAMEDATA.BAT").unlink(missing_ok=True)
        _child(folder, "inuse.flg").unlink(missing_ok=True)
    if rc != 0:
        raise GoldenError(f"{stem} -Y exited {rc} (transcript: {log})")


def reset(folder: Path, recipe: DosRecipe, dos: Dosemu, transcript: Path) -> None:
    """Drive `<GAME>.EXE RESET` to a new game, answering what turns up.

    Confirm, then the Configuration Editor opens; only after ESCaping out of it
    does the league-wide question appear, and only on the node whose address
    matches the nodes file's HOST entry.
    """
    from sr_harness.session import DosSession, expand

    _batch(folder, "RESET.BAT", dos.dos_path(folder), f"{recipe.exe.rsplit('.', 1)[0]} RESET")
    _child(folder, "inuse.flg").unlink(missing_ok=True)
    session = DosSession(dos.command(folder, "RESET.BAT"), transcript=str(transcript))
    try:
        if not session.until(r"Configuration Editor", [(r"reset the Game", "Y")], timeout=180):
            raise GoldenError(f"RESET never reached the config editor in {folder}\n"
                              f"--- screen ---\n{session.screen_text()}")
        # dosemu takes a lone ESC as the start of an escape sequence and
        # swallows it; pressing again gets one through.
        session.mash(expand("<ESC>"), "Configuration Editor", max_presses=80)
        if session.wait_for(r"league-wide reset", timeout=60):
            session.send("n")
        session.pump(20)
    finally:
        session.close()
        # RESET deletes stray .BAT files itself; this is for when it did not run.
        (folder / "RESET.BAT").unlink(missing_ok=True)
        _child(folder, "inuse.flg").unlink(missing_ok=True)


def missing_data(folder: Path, recipe: DosRecipe) -> list[str]:
    data = _child(folder, "DATA")
    have = {p.name.lower() for p in data.iterdir()} if data.is_dir() else set()
    return [f"DATA/{f}" for f in recipe.required_data if f.lower() not in have]


def trial(image: Path, recipe: DosRecipe, dos: Dosemu) -> None:
    """RESET a throwaway copy of the image as one-node league 999."""
    copy = dos.drive_c / "GOLDEN" / ("T" + secrets.token_hex(3).upper())
    install_image(image, copy)
    try:
        address = f"{TRIAL_LEAGUE}:{TRIAL_LEAGUE}/1"
        (copy / "bbs.cfg").write_bytes(_crlf("Nova Admin", "Golden Trial", address,
                                             f"{dos.dos_path(copy)}\\INBOUND",
                                             f"{dos.dos_path(copy)}\\NETMAIL",
                                             TRIAL_LEAGUE, "NONE"))
        (copy / recipe.nodes_file).write_bytes(_crlf("1 HOST", "Golden Trial", address,
                                                     "Nowhere", "XX", "XXX", ""))
        reset(copy, recipe, dos, dos.log_dir / f"golden_{recipe.prefix}_trial_reset.log")
        missing = missing_data(copy, recipe)
        if missing:
            raise GoldenError(f"RESET of a copy of the image did not make {', '.join(missing)}")
    finally:
        shutil.rmtree(copy, ignore_errors=True)


def default_version(media: Path) -> str:
    """sj1-r1 for bre_sj1.zip: the media's own name, and the recipe."""
    stem = media.stem.lower()
    for prefix in ("bre_", "fe_", "bre-", "fe-"):
        if stem.startswith(prefix):
            stem = stem[len(prefix):]
    return f"{stem}-r{RECIPE}"


def build_dos_image(game: str, media: Path, out_dir: Path, dos: Dosemu,
                    version: Optional[str] = None, say: Callable[[str], None] = print) -> Path:
    """Make <dirname>.tar.gz in out_dir from BRE or FE media. Returns its path."""
    recipe = RECIPES.get(game)
    if recipe is None:
        raise GoldenError(f"{game!r} is not a DOS game (B or F)")
    media = Path(media)
    version = version or default_version(media)
    dirname = image_dirname(game, version)
    out_dir = Path(out_dir)
    if (out_dir / dirname).exists() or (out_dir / f"{dirname}.tar.gz").exists():
        raise GoldenError(f"{dirname} is already in {out_dir}; a changed image needs a new version")
    work = dos.drive_c / "GOLDEN" / ("G" + secrets.token_hex(3).upper())
    work.parent.mkdir(parents=True, exist_ok=True)
    try:
        unpacked = work.with_name(work.name + ".Z")
        game_dir = unpack_media(media, unpacked)
        game_dir.rename(work)
        shutil.rmtree(unpacked)
        for name in (recipe.exe, recipe.data_exe):
            if not _child(work, name).is_file():
                raise GoldenError(f"{media.name} has no {name}: is it {recipe.prefix.upper()} media?")
        gone = clean(work)
        say(f"took out {len(gone)} files of the donor's league")
        game_files = sorted(p.name for p in _child(work, "GAME").iterdir())
        regenerate_game(work, recipe, dos)
        say(f"regenerated GAME/ ({len(game_files)} files)")
        problems = case_twins(work)
        after = sorted(p.name for p in _child(work, "GAME").iterdir())
        if after != game_files:
            problems.append(f"-Y changed GAME/'s names: {sorted(set(after) ^ set(game_files))}")
        leftovers = [p for p in work.iterdir() if p.is_file() and p.name.lower() in DROP]
        problems += [f"{p.name} is still there" for p in leftovers]
        if problems:
            raise GoldenError("; ".join(problems))
        staged = out_dir / dirname
        out_dir.mkdir(parents=True, exist_ok=True)
        shutil.move(str(work), str(staged))
        write_manifest(staged, game=game, version=version, recipe=RECIPE,
                       source={"name": media.name, "sha256": sha256(media)})
        trial(staged, recipe, dos)
        say("a RESET of a copy made a game")
        archive = pack_image(staged, out_dir)
        shutil.rmtree(staged)
        return archive
    except ImageError as e:
        raise GoldenError(str(e))
    finally:
        shutil.rmtree(work, ignore_errors=True)
        shutil.rmtree(work.with_name(work.name + ".Z"), ignore_errors=True)
        shutil.rmtree(out_dir / dirname, ignore_errors=True)


def build_ib_image(binary: Path, version: str, out_dir: Path) -> Path:
    """Make ib-<version>.tar.gz in out_dir from an Immortal Barons binary."""
    from backend.services.game_images import build_ib_image as build

    dirname = image_dirname("I", version)
    staged = Path(out_dir) / dirname
    if staged.exists() or (Path(out_dir) / f"{dirname}.tar.gz").exists():
        raise GoldenError(f"{dirname} is already in {out_dir}")
    staged.mkdir(parents=True)
    try:
        build(Path(binary), version, staged)
        return pack_image(staged, Path(out_dir))
    finally:
        shutil.rmtree(staged, ignore_errors=True)
